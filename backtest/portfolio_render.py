"""The portfolio backtest's reports as Markdown: the blind check (counts only) and the scored
run (`docs/backtests/portfolio-preregistration.md` §5-§7)."""

from __future__ import annotations

from auratrade.config import RiskConfig
from backtest import portfolio as pf
from backtest import portfolio_report as pr


def pct(x: float) -> str:
    return f"{x:+.1%}"


def share(x: float) -> str:
    return f"{x:.1%}"


def months(x: float | None) -> str:
    return "not recovered" if x is None else f"{x:.0f}"


def _source(history_note: str, fetched: str, risk: RiskConfig) -> str:
    return (
        f"Pre-registration: `docs/backtests/portfolio-preregistration.md`, approved at commit "
        f"`{pf.PREREGISTRATION_COMMIT}`; `risk.yaml` hash `{risk.short_hash}`. "
        f"Market file: Kenneth French's daily factors ({history_note.rstrip('.')}), "
        f"fetched {fetched}."
    )


def render_blind(result: pf.Blind, risk: RiskConfig, stamp: str) -> str:
    h, c = result.history, result.counts
    days = h.days
    lines = [
        "# The portfolio manager: the blind mechanics check (task 3.22)",
        "",
        f"Generated by `uv run python -m backtest.portfolio --blind` on {stamp}. "
        + _source(h.note, h.fetched_at, risk),
        "",
        "**Counts, invariants and data checks only** (pre-registration §7): nothing here measures"
        " how the strategy did. Every invariant held (a failure stops the run with an error).",
        "",
        f"Scored period: cash at the close of {days[result.period.start]}, sold at the close of"
        f" {days[result.period.end]}. Rolling 10-year windows: {result.window_count}.",
        "",
        "## Stop conditions",
        "",
    ]
    if result.stops:
        lines += [f"- **{s}**" for s in result.stops]
        lines += ["", "**The work stops here and goes to the user before the scored run.**"]
    else:
        lines.append("None fired: the scored run (3.23) may go ahead, with the user.")
    lines += [
        "",
        "## Data checks (§4.4)",
        "",
        "| Check | Sessions | Daily correlation | Annualized gap | Result |",
        "|---|---|---|---|---|",
    ]
    for k in result.checks:
        lines.append(
            f"| {k.name} | {k.sessions} | {k.correlation:.4f} | {k.cagr_gap:.2%} |"
            f" {'pass' if k.passed else '**fail**'} |"
        )
    lines += ["", "Gaps of more than 7 days between sessions:", ""]
    lines += [
        f"- {a} to {b}: {'a known closure' if known else '**not expected**'}"
        for a, b, known in result.gaps
    ] or ["- none"]
    lines += [
        "",
        "## Sessions and flips by decade",
        "",
        "| Decade | Sessions | Flips |",
        "|---|---|---|",
    ]
    for decade in sorted(result.sessions_by_decade):
        lines.append(
            f"| {decade} | {result.sessions_by_decade[decade]} |"
            f" {result.flips_by_decade.get(decade, 0)} |"
        )
    lines += [
        "",
        "## The primary's mechanics",
        "",
        "| Count | Value |",
        "|---|---|",
        f"| Flips a year | {c.flips_a_year:.2f} |",
        f"| R's in UP / DOWN | {share(c.up)} / {share(c.down)} |",
        f"| R's under the cap / halted | {share(c.capped)} / {share(c.halted)} |",
        f"| Trades a year | {c.trades_a_year:.1f} |",
        f"| Stop-outs | {c.stopouts} |",
        f"| Lots opened (buys and reinvested payouts) | {c.lots_opened} |",
    ]
    return "\n".join(lines) + "\n"


def _metrics_row(name: str, m: pr.Metrics) -> str:
    return (
        f"| {name} | {pct(m.cagr_after_tax)} | {pct(m.cagr_before_tax)} | {share(m.max_drawdown)} |"
        f" {share(m.volatility)} | {m.return_over_drawdown:.2f} | {pct(m.worst_year)} |"
    )


METRICS_HEAD = [
    "| | CAGR after tax | CAGR before tax | Max drawdown | Volatility | CAGR ÷ max DD"
    " | Worst year |",
    "|---|---|---|---|---|---|---|",
]


def render_scored(result: pf.Scored, risk: RiskConfig, stamp: str) -> str:
    h, g = result.history, result.gate
    bt = risk.portfolio.backtest
    first, last = result.days
    main, bench = result.primary.metrics, result.benchmark.metrics
    excess = [w.excess for w in result.windows]
    lines = [
        "# The portfolio manager: the scored run (task 3.23)",
        "",
        f"Generated by `uv run python -m backtest.portfolio` on {stamp}. "
        + _source(h.note, h.fetched_at, risk),
        f"Period: cash at the close of {first}, everything sold at the close of {last}."
        " **Committed as produced, before it is read for meaning** (§2 step 4); the Reading is"
        " written after.",
        "",
        "## The gate",
        "",
        "| | Condition | Value | Result |",
        "|---|---|---|---|",
        f"| G1 | After-tax CAGR above the benchmark's | {pct(main.cagr_after_tax)} vs"
        f" {pct(bench.cagr_after_tax)} ({pct(g.cagr_gap)}) | {'pass' if g.g1 else '**fail**'} |",
        f"| G2 | Max drawdown no deeper | {share(main.max_drawdown)} vs {share(bench.max_drawdown)}"
        f" | {'pass' if g.g2 else '**fail**'} |",
        f"| G3 | Ahead after tax in ≥ {bt.min_window_share:.0%} of the {len(result.windows)}"
        f" rolling 10-year windows | {share(g.window_share)} | {'pass' if g.g3 else '**fail**'} |",
        "",
        f"**Verdict: {g.verdict}.** (A near miss: G2 holds and the after-tax CAGR is at most"
        f" {bt.near_miss_cagr:.0%} a year behind, §5.3.)",
        "",
        "## Performance",
        "",
        *METRICS_HEAD,
        _metrics_row("Strategy (the twin's rules)", main),
        _metrics_row("Benchmark (bought, held, sold at the end)", bench),
        "",
        f"The windows' after-tax excess CAGR: median {pct(pr.percentile(excess, 0.5))}, 10th"
        f" percentile {pct(pr.percentile(excess, 0.1))}, 90th {pct(pr.percentile(excess, 0.9))}.",
        "",
        f"Daily excess over the benchmark before tax, mean x 252: {pct(result.bootstrap.mean)};"
        f" {bt.confidence:.0%} block-bootstrap interval ({bt.bootstrap_block_sessions}-session"
        f" blocks, {bt.bootstrap_samples} draws): {pct(result.bootstrap.low)} to"
        f" {pct(result.bootstrap.high)}. Reported; it gates nothing.",
        "",
        "## After publication",
        "",
        "| Since | Strategy after tax | Benchmark after tax | Strategy max DD | Benchmark max DD |",
        "|---|---|---|---|---|",
    ]
    for name, since, s, b in result.published:
        lines.append(
            f"| {since} ({name}) | {pct(s.cagr_after_tax)} | {pct(b.cagr_after_tax)} |"
            f" {share(s.max_drawdown)} | {share(b.max_drawdown)} |"
        )
    lines += [
        "",
        "## By decade (before tax, on the marks)",
        "",
        "| Decade | Strategy | Benchmark |",
        "|---|---|---|",
    ]
    lines += [f"| {d} | {pct(s)} | {pct(b)} |" for d, s, b in result.decades]
    lines += [
        "",
        "## The crashes (after tax)",
        "",
        "| Crash | Strategy fall | Benchmark fall | Strategy months to recover"
        " | Benchmark months |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {c.name} | {share(c.strategy_fall)} | {share(c.benchmark_fall)} |"
        f" {months(c.strategy_months)} | {months(c.benchmark_months)} |"
        for c in result.crashes
    ]
    lines += [
        "",
        "## Activity (the strategy)",
        "",
        "| | Value |",
        "|---|---|",
        f"| Flips a year | {main.flips_a_year:.2f} |",
        f"| Tax paid a year, of average equity | {share(main.tax_a_year)} |",
        f"| R's in UP / DOWN | {share(main.up)} / {share(main.down)} |",
        f"| R's volatility-capped / halted | {share(main.capped)} / {share(main.halted)} |",
        f"| Stop-outs / halts | {main.stopouts} / {main.halt_starts} |",
        "",
        "## The comparisons and the diagnostics (reported, never adopted, §6)",
        "",
        "| | Change | CAGR after tax | CAGR before tax | Max drawdown | Flips a year"
        " | Margin calls |",
        "|---|---|---|---|---|---|---|",
    ]
    for config, m in [*result.compared, *result.diagnostics]:
        lines.append(
            f"| {config.name} | {config.change} | {pct(m.cagr_after_tax)}"
            f" | {pct(m.cagr_before_tax)}"
            f" | {share(m.max_drawdown)} | {m.flips_a_year:.2f} | {m.margin_calls} |"
        )
    lines += ["", "## Reading", "", "_To be written after this report is committed as produced._"]
    return "\n".join(lines) + "\n"
